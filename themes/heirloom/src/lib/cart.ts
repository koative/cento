import { useSyncExternalStore } from "react";
import type { Art, Metal } from "../content";

export type CartLine = {
  key: string;
  /** Piece slug, or "custom" for a ring-builder design. */
  slug: string;
  name: string;
  metal: Metal;
  art: Art;
  /** Human-readable options: size, chain, stone, engraving. */
  details: string[];
  unit: number;
  qty: number;
};

const STORAGE_KEY = "heirloom-bag";
const MAX_QTY = 5;
const listeners = new Set<() => void>();

function load(): CartLine[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? (JSON.parse(raw) as CartLine[]) : [];
  } catch {
    return [];
  }
}

let lines = load();

function set(next: CartLine[]) {
  lines = next;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(next));
  } catch {
    /* storage unavailable: the bag still works for this visit */
  }
  listeners.forEach((l) => l());
}

export function useCart() {
  return useSyncExternalStore(
    (l) => (listeners.add(l), () => listeners.delete(l)),
    () => lines,
  );
}

export function addLine(line: Omit<CartLine, "key">) {
  const key = [
    line.slug,
    line.metal,
    ...line.details,
    JSON.stringify(line.art),
  ].join("|");
  const found = lines.find((l) => l.key === key);
  set(
    found
      ? lines.map((l) =>
          l === found ? { ...l, qty: Math.min(l.qty + line.qty, MAX_QTY) } : l,
        )
      : [...lines, { ...line, key }],
  );
}

export function setQty(key: string, qty: number) {
  set(
    qty < 1
      ? lines.filter((l) => l.key !== key)
      : lines.map((l) =>
          l.key === key ? { ...l, qty: Math.min(qty, MAX_QTY) } : l,
        ),
  );
}

export function clearCart() {
  set([]);
}

export const maxQty = MAX_QTY;
export const count = (cart: CartLine[]) => cart.reduce((s, l) => s + l.qty, 0);
export const subtotal = (cart: CartLine[]) =>
  cart.reduce((s, l) => s + l.qty * l.unit, 0);
export const money = (n: number) => "$" + n.toLocaleString("en-US");
